let LANG = 'ja';
function t(ja, ...args) {
  let s = LANG === 'en' && EN[ja] != null ? EN[ja] : ja;
  args.forEach((a, i) => { s = s.split('{' + i + '}').join(a); });
  return s;
}
function setLang(l) { LANG = l === 'en' ? 'en' : 'ja'; document.documentElement.lang = LANG; }
// Translates the static page (text nodes, title / placeholder attributes) once, at start.
function translateDom() {
  if (LANG !== 'en') return;
  const w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  for (let n = w.nextNode(); n; n = w.nextNode()) {
    const raw = n.nodeValue, key = raw.trim();
    if (key && EN[key] != null) n.nodeValue = raw.replace(key, EN[key]);
    else if (EN[raw] != null) n.nodeValue = EN[raw];
  }
  document.querySelectorAll('[title],[placeholder]').forEach(e => {
    for (const a of ['title', 'placeholder']) if (e.hasAttribute(a) && EN[e.getAttribute(a)] != null) e.setAttribute(a, EN[e.getAttribute(a)]);
  });
}
